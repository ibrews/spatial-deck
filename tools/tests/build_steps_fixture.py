#!/usr/bin/env python3
"""Build the step-contract fixture decks from the template (tools/tests/steps_fixture/{good,broken}.html).
good.html uses only well-behaved modules: the steps sweep must PASS. broken.html adds three modules that each break the
contract a different way: the sweep must FAIL on exactly those three slides. Run by tools/tests/test_steps.sh."""
import re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FX = HERE / "steps_fixture"
TEMPLATE = (HERE.parent.parent / "index.html").read_text(encoding="utf-8")
A, B = "<!-- ── SD SLIDE MODULES START ── -->", "<!-- ── SD SLIDE MODULES END ── -->"

GOOD = [{"use": "test/counter"}, {"use": "test/beats"}, {"use": "test/counter", "props": {"title": "Counter, 3 lines", "lines": ["x", "y", "z"]}, "steps": 3}]
BROKEN = GOOD + [{"use": "test/dead"}, {"use": "test/frame-liar"}, {"use": "test/sneaky"}]


def deck(cases):
    import json
    sec = "const SECTIONS = [\n  { year: 'FIXTURE', accent: 'teal', lesson: { title: 'Step contract fixture', short: 'FIXTURE', tagline: 'Generated by tools/tests/build_steps_fixture.py', tags: '' },\n    cases: " + json.dumps(cases) + " },\n];\n"
    s, n = re.subn(r"const SECTIONS = \[.*?\n\];\n", lambda m: sec, TEMPLATE, count=1, flags=re.S)
    if not n:
        sys.exit("build_steps_fixture: template SECTIONS block not found")
    tags = "".join(f'<script src="slides/{p.parent.parent.name}/{p.parent.name}/slide.js"></script>\n' for p in sorted(FX.glob("slides/*/*/slide.js")))
    s = re.sub(re.escape(A) + r".*?" + re.escape(B), lambda m: A + "\n" + tags + B, s, count=1, flags=re.S)
    return s


(FX / "good.html").write_text(deck(GOOD), encoding="utf-8")
(FX / "broken.html").write_text(deck(BROKEN), encoding="utf-8")
src = HERE.parent.parent / "slides" / "sd-frame.js"
(FX / "slides" / "sd-frame.js").write_bytes(src.read_bytes())
(FX / "favicon.svg").write_bytes((HERE.parent.parent / "favicon.svg").read_bytes())
print("build_steps_fixture: wrote good.html, broken.html")
