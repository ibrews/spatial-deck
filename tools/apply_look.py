#!/usr/bin/env python3
"""Inline the Spatial Deck style library (styles/) into a deck so its look can be picked at runtime.

The library stays as separate source files (styles/base.css, styles/looks/<id>/look.{css,json,md}); the deck stays a
single file. This writes, between sentinels, into the deck's index.html:
  - one Google Fonts link for every look's faces, and one <style> with base.css + every look.css, with the scope
    placeholders expanded (`:look` -> body[data-look="<id>"], `:looked` -> any look except noir, at zero added specificity);
  - the look runtime: picks the look from ?look=<id>, else body[data-look] (a talk's options picker may set it),
    else window.SD_LOOK, else the --default; builds the look frame (#sd-frame: title block / running head /
    masthead); tags motion iframes with window.name "sd-look:<id>" so they can recolor themselves offline.
With --motion-dir it also writes <dir>/look.js (the motion recolorer, palettes from each look.json) and adds
<script src="look.js"></script> to every seekable motion graphic there. Idempotent; re-run after editing styles/.
    python3 tools/apply_look.py                                   # the template itself
    python3 tools/apply_look.py --html ../my-talk/index.html --styles styles --motion-dir ../my-talk/media/motion
"""
import argparse, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ("https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,100..900&family=IBM+Plex+Mono:wght@400;500;600"
         "&family=Newsreader:ital,opsz,wght@0,6..72,200..800;1,6..72,200..800&family=Big+Shoulders+Display:wght@100..900&display=swap")
HEAD_A, HEAD_B = "<!-- ── SD LOOKS START ── -->", "<!-- ── SD LOOKS END ── -->"
BODY_A, BODY_B = "<!-- ── SD LOOK RUNTIME START ── -->", "<!-- ── SD LOOK RUNTIME END ── -->"

RUNTIME = r"""<script>
// ── Spatial Deck looks runtime (tools/apply_look.py) ──
(function(){
  const LOOKS=@@LOOKS@@;const P=new URLSearchParams(location.search);
  let look=P.get('look')||document.body.dataset.look||window.SD_LOOK||'@@DEFAULT@@';if(!LOOKS.includes(look))look='noir';
  document.body.dataset.look=look;window.SD_ACTIVE_LOOK=look;
  const tag=f=>{if(/media\/motion\//.test(f.getAttribute('src')||''))f.name='sd-look:'+look;};
  document.querySelectorAll('iframe').forEach(tag);
  new MutationObserver(ms=>ms.forEach(m=>m.addedNodes.forEach(n=>{if(n.tagName==='IFRAME')tag(n);else if(n.querySelectorAll)n.querySelectorAll('iframe').forEach(tag);}))).observe(document.body,{childList:true,subtree:true});
  if(look==='noir')return;
  // chapter badges "1 / 8" become two parts so each look can typeset them (callout circle, folio numeral, No. x of y)
  document.querySelectorAll('.ey-badge').forEach(b=>{const m=/^\s*(\d+)\s*\/\s*(\d+)\s*$/.exec(b.textContent);if(m)b.innerHTML=`<i class="n">${m[1]}</i><i class="of">${m[2]}</i>`;});
  const meta=n=>document.querySelector(`meta[name="${n}"]`)?.content||'';
  const project=meta('sd-project')||document.title.split(/\s[—|–-]\s/)[0];const who=meta('author'),ev=meta('sd-event');
  const fr=document.createElement('div');fr.id='sd-frame';fr.setAttribute('aria-hidden','true');
  fr.innerHTML=`<span class="f-project"><b>Project</b>${project}</span>${who||ev?`<span class="f-meta"><b>${who?'Presented by':'Event'}</b>${[who,ev].filter(Boolean).join(' &middot; ')}</span>`:''}<span class="f-sheet"><b>Sheet</b><i></i></span>`;
  // inside #deck, so in stage mode (a scaled 1920x1080 box) the frame scales with the slides instead of the window
  (document.getElementById('deck')||document.body).appendChild(fr);const num=fr.querySelector('.f-sheet i');const deck=document.getElementById('deck');
  const pad=n=>String(n).padStart(2,'0');
  function upd(){const all=typeof allSlides!=='undefined'?allSlides:[...deck.querySelectorAll('.slide')];
    const vis=all.filter(s=>s.dataset.hidden!=='1'&&s.dataset.type!=='settings');const a=deck.querySelector('.slide.active');const i=vis.indexOf(a);
    num.textContent=i<0?'':pad(i+1)+' / '+pad(vis.length);fr.style.visibility=(!a||a.dataset.type==='settings'||a.dataset.type==='cover')?'hidden':'';}
  if(deck){new MutationObserver(upd).observe(deck,{subtree:true,attributes:true,attributeFilter:['class','data-hidden']});upd();}
})();
</script>"""

MOTION_JS = r"""/* Spatial Deck motion recolorer (generated by tools/apply_look.py from each styles/looks/<id>/look.json; do not edit).
   A seekable motion graphic authored in the noir palette loads this last; for any other look it rewrites its colors,
   fonts and glow filters in place. Look comes from ?look=<id>, else window.name "sd-look:<id>" (set by the deck,
   works offline from file://), else the parent deck's body[data-look] when same-origin. */
(function(){
  var SRC=@@SRC@@,LOOKS=@@LOOKS@@;
  var look=new URLSearchParams(location.search).get('look');
  if(!look){var m=/sd-look:([\w-]+)/.exec(window.name||'');if(m)look=m[1];}
  if(!look){try{if(parent!==window)look=parent.document.body.dataset.look;}catch(e){}}
  var L=LOOKS[look];if(!L)return;document.documentElement.dataset.look=look;
  function rgb(h){h=h.replace('#','');return [parseInt(h.substr(0,2),16),parseInt(h.substr(2,2),16),parseInt(h.substr(4,2),16)];}
  var pairs=[];Object.keys(SRC).forEach(function(k){if(L.palette[k])pairs.push([SRC[k].toLowerCase(),L.palette[k]]);});
  function recolor(s){if(!s)return s;
    pairs.forEach(function(p){var a=rgb(p[0]),b=rgb(p[1]);
      s=s.replace(new RegExp(p[0]+'(?![0-9a-f])','gi'),p[1]);
      s=s.replace(new RegExp('rgb(a?)\\(\\s*'+a[0]+'\\s*,\\s*'+a[1]+'\\s*,\\s*'+a[2]+'\\s*([,)])','g'),function(_,x,end){return 'rgb'+x+'('+b.join(',')+end;});});
    if(L.palette.white){s=s.replace(/#fff(?![0-9a-f])/gi,L.palette.white).replace(/(^|[:\s"'])white(?=[;\s"')]|$)/g,'$1'+L.palette.white);}
    s=s.replace(/'Space Grotesk'|"Space Grotesk"|Space Grotesk|'Inter'|"Inter"/g,"'"+L.font+"'");
    if(L.blend)s=s.replace(/mix-blend-mode\s*:\s*(screen|lighten|plus-lighter)/g,'mix-blend-mode:'+L.blend);  // light paper: screen would wash out
    if(L.stripGlow)s=s.replace(/filter\s*:\s*drop-shadow\([^;}"]*\)/g,'filter:none').replace(/text-shadow\s*:[^;}"]*/g,'text-shadow:none');
    return s;}
  [].forEach.call(document.querySelectorAll('style'),function(st){st.textContent=recolor(st.textContent);});
  var ATTR=['fill','stroke','stop-color','flood-color','color','style'];
  [].forEach.call(document.querySelectorAll('*'),function(el){ATTR.forEach(function(a){var v=el.getAttribute(a);if(v){var r=recolor(v);if(r!==v)el.setAttribute(a,r);}});});
  if(L.stripGlow){var glow={};[].forEach.call(document.querySelectorAll('filter'),function(f){if(f.querySelector('feGaussianBlur,feDropShadow'))glow[f.id]=1;});
    [].forEach.call(document.querySelectorAll('[filter]'),function(el){var m=/url\(#([^)]+)\)/.exec(el.getAttribute('filter'));if(m&&glow[m[1]])el.removeAttribute('filter');});}
  var ln=document.createElement('link');ln.rel='stylesheet';ln.href=@@FONTS@@;document.head.appendChild(ln);
})();
"""


def expand(css, look_id=None):
    # Specificity ladder: template rules (classes only, up to 4) < base (one id via :not(#_)) < a look (id + attr).
    # :not(#_) matches every body and adds id weight; :where() keeps the base's own attributes out of the count.
    css = css.replace(":looked", 'body:where([data-look]:not([data-look="noir"])):not(#_)')
    if look_id:
        css = css.replace(":look", f'body[data-look="{look_id}"]:not(#_)')
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S).strip()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--html", default=str(ROOT / "index.html"))
    ap.add_argument("--styles", default=str(ROOT / "styles"), help="style library folder (default: this repo's styles/)")
    ap.add_argument("--default", default="noir", help="look when nothing picks one (default: noir, the template's original)")
    ap.add_argument("--motion-dir", help="folder of seekable motion graphics to give the recolorer")
    a = ap.parse_args()
    styles, html = Path(a.styles), Path(a.html)
    looks = sorted(p.parent.name for p in (styles / "looks").glob("*/look.css"))
    css = [expand((styles / "base.css").read_text(encoding="utf-8"))]
    meta = {}
    for lid in looks:
        css.append(expand((styles / "looks" / lid / "look.css").read_text(encoding="utf-8"), lid))
        meta[lid] = json.loads((styles / "looks" / lid / "look.json").read_text(encoding="utf-8"))
    if a.default != "noir" and a.default not in looks:
        sys.exit(f"apply_look: unknown --default {a.default!r}; looks: noir, {', '.join(looks)}")
    s = html.read_text(encoding="utf-8")
    head = f'{HEAD_A}\n<link href="{FONTS}" rel="stylesheet">\n<style id="sd-looks">\n' + "\n".join(css) + f"\n</style>\n{HEAD_B}"
    run = BODY_A + "\n" + RUNTIME.replace("@@LOOKS@@", json.dumps(["noir"] + looks)).replace("@@DEFAULT@@", a.default) + "\n" + BODY_B
    for A, B, block, anchor in ((HEAD_A, HEAD_B, head, "</head>"), (BODY_A, BODY_B, run, "</body>")):
        if A in s:
            s = re.sub(re.escape(A) + r".*?" + re.escape(B), lambda m: block, s, count=1, flags=re.S)
        else:
            i = s.rfind(anchor) if anchor == "</body>" else s.find(anchor)
            if i < 0:
                sys.exit(f"apply_look: {anchor} not found in {html}")
            s = s[:i] + block + "\n" + s[i:]
    html.write_text(s, encoding="utf-8")
    print(f"apply_look: {html} — looks noir (original), {', '.join(looks)}; default {a.default}")
    if a.motion_dir:
        md = Path(a.motion_dir)
        src = next(iter(meta.values()))["motionSource"] if meta else {}
        pal = {k: v["motion"] for k, v in meta.items()}
        js = MOTION_JS.replace("@@SRC@@", json.dumps(src)).replace("@@LOOKS@@", json.dumps(pal)).replace("@@FONTS@@", json.dumps(FONTS))
        (md / "look.js").write_text(js, encoding="utf-8")
        n = 0
        for f in sorted(md.glob("*.html")):
            t = f.read_text(encoding="utf-8")
            if 'src="look.js"' not in t and "</body>" in t:
                f.write_text(t.replace("</body>", '<script src="look.js"></script>\n</body>', 1), encoding="utf-8"); n += 1
        print(f"apply_look: wrote {md / 'look.js'}; added it to {n} motion graphic(s)")


if __name__ == "__main__":
    main()
